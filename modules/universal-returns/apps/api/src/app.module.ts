import { createRelayHealthController } from '@gigalibs/module-sdk';
import { Module } from '@nestjs/common';
import { AuthorizationGuard } from './authorization.js';
import { runtimeConfigProvider } from './config.js';
import { DatabaseService } from './database.service.js';
import { HealthController } from './health.controller.js';
import { RecordsController } from './records/records.controller.js';
import { RecordsService } from './records/records.service.js';
import { InventoryHandshakeClient } from './inventory/inventory-handshake.client.js';
import { RmaController } from './rma/rma.controller.js';
import { RmaService } from './rma/rma.service.js';
import {
  RETURNS_FINANCE_RELAY_CONFIG,
  RETURNS_ORDERS_RELAY_CONFIG,
  loadReturnsFinanceRelayConfig,
  loadReturnsOrdersRelayConfig,
} from './relay/relay-config.js';
import { ReturnsFinanceOutboxRelay } from './relay/returns-finance-relay.js';
import { ReturnsOrdersOutboxRelay } from './relay/returns-orders-relay.js';

const ReturnsRelayHealthController = createRelayHealthController('v1/health');

/** Returns and RMA runtime, generated by `pnpm module:new` (WI-OI-085) on the module SDK. */
@Module({
  controllers: [HealthController, ReturnsRelayHealthController, RecordsController, RmaController],
  providers: [
    { provide: RETURNS_ORDERS_RELAY_CONFIG, useFactory: () => loadReturnsOrdersRelayConfig() },
    { provide: RETURNS_FINANCE_RELAY_CONFIG, useFactory: () => loadReturnsFinanceRelayConfig() },
    ReturnsOrdersOutboxRelay,
    ReturnsFinanceOutboxRelay,
    runtimeConfigProvider,
    DatabaseService,
    AuthorizationGuard,
    RecordsService,
    InventoryHandshakeClient,
    RmaService,
  ],
})
export class AppModule {}
